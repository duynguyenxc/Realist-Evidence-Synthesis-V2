#!/usr/bin/env python3
"""Report the adjudication of the concepts most likely to be spurious.

WHAT QUESTION THIS ANSWERS
--------------------------
Verification has only ever measured RECALL against Richmond's 46 concepts.
Precision — how much of what the system extracted is junk — has never been
measured, and it is the first thing a methods reviewer asks. Measuring it properly
needs a human to read a sample, which needs time this project has not had.

What could be done at no cost was to bound the question, and that was done: of the
system's 183 concepts, 24 are the ones Richmond's gold entities map onto and 159
lie outside that frame. Being outside Richmond's frame is not an error — Richmond
reported what they chose to report — so the bound says nothing on its own. But
within it, one subset is where spurious extraction would hide if it existed: the
concepts supported by a SINGLE mention in a SINGLE study. There are 79.

So all 79 were adjudicated one at a time, each against its own verbatim quote,
and the verdicts are in `outputs/analysis/singles_adjudication.json`.

WHO DID THE ADJUDICATING, AND WHY THAT MATTERS
----------------------------------------------
Claude, in conversation with the RA — not the pipeline, and not a human coder.
That is a real limitation and it is stated wherever the figures appear, for two
reasons. The extractor is a model of the same family, so self-preference is
possible; and this project has already measured how much judges disagree, finding
programme-theory correspondence at 0.82 or 0.53 depending on the judge's model
family. **This is a triage that tells a human where to look, not a measurement.**

The verdicts are five, and the distinction between the middle two is the point:

  general     a usable concept that happens to lie outside Richmond's frame
  local       correctly extracted and quote-supported, but naming something
              specific to one study, so it cannot recur across the corpus
  over_split  should have merged with another concept — a normalisation failure
  role        wrong entity type, or a label that contradicts its own quote
  not_theory  quote-supported but not an element of any programme theory

`local` is the category a precision figure alone would get wrong. A concept that
names one study's stimulus set is not spurious — the extraction is right and the
quote supports it — but it cannot do any analytic work. Counting it as a hit
overstates the system; counting it as an error understates it. It needs its own
row, which is why precision as a single number was the wrong target.

USAGE
-----
    python scripts/precision_sample.py
"""

from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]

ORDER = ["general", "local", "over_split", "role", "not_theory"]
TITLE = {
    "general": "Usable concept, outside Richmond's frame",
    "local": "Correct but study-local — cannot recur",
    "over_split": "Should have merged with another concept",
    "role": "Wrong type, or label contradicts its quote",
    "not_theory": "Quote-supported but not a programme-theory element",
}
DEFECTS = {"over_split", "role", "not_theory"}


def main() -> int:
    src = PROJECT_ROOT / "outputs" / "analysis" / "singles_adjudication.json"
    if not src.exists():
        print(f"No adjudication at {src}", file=sys.stderr)
        return 1
    adj = json.loads(src.read_text(encoding="utf-8"))
    n = len(adj)
    by = collections.Counter(v["verdict"] for v in adj.values())
    by_type = collections.Counter(v["type"] for v in adj.values())
    defects = {k: v for k, v in adj.items() if v["verdict"] in DEFECTS}

    L: list[str] = []
    w = L.append
    w("# Adjudicating the concepts where spurious extraction would hide")
    w("")
    w("Generated by `scripts/precision_sample.py` from "
      "`outputs/analysis/singles_adjudication.json`.")
    w("")
    w("## What was adjudicated, and why these")
    w("")
    w("Verification has only ever measured recall against the 46 concepts in the gold "
      "standard. Precision has never been measured. Of the system's 183 concepts, 24 are "
      "the ones the gold entities map onto and 159 lie outside that frame — which is not an "
      "error, since the review reported what it chose to report.")
    w("")
    w(f"Inside those 159 there is one subset where spurious extraction would show up if it "
      f"existed: concepts resting on a **single mention in a single study**. There are "
      f"**{n}**, and all {n} were adjudicated one at a time against their own verbatim "
      "quotes.")
    w("")
    w("> **Note on the count.** This was previously reported as 72. That figure used the "
      "pre-correction set of 31 matched concepts; with the 24 that survive the matcher fix "
      "of 2026-11-04, the correct number is 79. Several gold entities map onto the same "
      "system concept, which is why 31 gold matches do not give 31 distinct concepts.")
    w("")
    w("**Who judged.** Claude, in conversation with the RA — not the pipeline, and not a "
      "human coder. The extractor is a model of the same family, so self-preference is "
      "possible, and this project has already measured judges disagreeing by 0.31 on "
      "identical inputs. **Treat what follows as a triage that says where a human should "
      "look, not as a measurement.**")
    w("")
    w("## Result")
    w("")
    w("| Verdict | What it means | Concepts | Share |")
    w("|---|---|---|---|")
    for k in ORDER:
        w(f"| `{k}` | {TITLE[k]} | **{by[k]}** | {by[k] / n:.0%} |")
    w("")
    correct = n - sum(by[k] for k in DEFECTS)
    w(f"**{correct} of {n} ({correct / n:.0%}) are correct extractions** — the quote supports "
      f"the concept and the type is right. **{sum(by[k] for k in DEFECTS)} ({sum(by[k] for k in DEFECTS) / n:.0%}) "
      "are defects.**")
    w("")
    w("Read that against what it is. This is the hardest subset of the output, chosen "
      "precisely because single-instance concepts are where extraction noise would collect. "
      "A defect rate of "
      f"{sum(by[k] for k in DEFECTS) / n:.0%} *here* implies a lower one across all 183, "
      "though how much lower is not something this sample can say.")
    w("")
    w(f"Of the {by['general'] + by['local']} correct extractions, **{by['general']} are "
      f"concepts that could do analytic work across studies** and **{by['local']} name "
      "something specific to one study**. The second group is the reason precision as a "
      "single number was the wrong target: a concept naming one study's stimulus set is "
      "extracted correctly and cannot be used, and neither 'hit' nor 'error' describes it.")
    w("")
    w("By entity type: " + ", ".join(f"**{t}** {c}" for t, c in by_type.most_common()) + ".")
    w("")
    w("## Every defect, with its reason")
    w("")
    w(f"All {len(defects)}. Nothing is summarised away.")
    w("")
    for k in ORDER:
        if k not in DEFECTS:
            continue
        rows = {cid: v for cid, v in defects.items() if v["verdict"] == k}
        if not rows:
            continue
        w(f"### `{k}` — {TITLE[k]} ({len(rows)})")
        w("")
        for cid, v in sorted(rows.items()):
            w(f"**`{cid}`** · {v['type']} · {v['study']}")
            w("")
            w(f"> {v['quote'][:300]}")
            w("")
            w(f"{v['reason'].strip()}")
            w("")
    in_rich = {k: v for k, v in adj.items() if v.get("in_richmond_body")}
    w("## Five of them are in Richmond's own paper")
    w("")
    w("The 159 concepts \"outside the frame\" are outside the **coded gold standard**, which was "
      "built from the five CMOC statements and figures. That is not the same as being outside "
      "**Richmond's paper**, and the difference matters, because the review says plainly why "
      "its frame is narrow:")
    w("")
    w("> \"The selected studies identified key contexts for clinical reasoning interventions at "
      "the individual level, with contexts at the teacher or the wider organisation level "
      "rarely discussed. Therefore, the results presented below predominantly focus on "
      "individual student level contexts.\"")
    w("")
    w(f"Reading the original paper (`data/paper-Richmond-original.pdf`) against these {n} "
      f"concepts, **{len(in_rich)} are discussed in Richmond's own analysis** while being "
      "absent from the gold standard:")
    w("")
    for cid, v in sorted(in_rich.items()):
        w(f"- **`{cid}`** — {v['label']}")
        w(f"  {v['in_richmond_body']}")
    w("")
    w("**How that figure was arrived at, including the part that was wrong.** A word-level "
      "overlap check first returned 19 of 79. Nineteen was contaminated: the matches were "
      "coming from Richmond's **reference list**, which contains the titles of the 28 included "
      "papers, so a concept named after one study's intervention matched its own citation. "
      "Restricting the search to the body text gave 12. Of those, six carried the claim, and "
      "each was then checked by locating an actual sentence — five held and one, "
      "`mech:self-explanation-examples`, did not: its words occur separately in Richmond's "
      "prose but nothing there discusses self-explanation examples. It is recorded in the "
      "data as a false positive rather than dropped. **19 to 12 to 5.** An automated overlap "
      "count would have reported the first number.")
    w("")
    w("What this changes: the system is not inventing concepts Richmond's authors would "
      "disown. For at least five, it recovered something the reviewers themselves wrote about "
      "and did not formalise into a CMOC. That is a finding about the **benchmark's** "
      "coverage, not only about the system's precision.")
    w("")
    w("## What follows from this")
    w("")
    w("**The five `over_split` verdicts have a single cause, and it is now fixed.** "
      "`_batched_cluster` clusters labels forty at a time and unions clusters across "
      "batches only when their canonical labels match exactly, so synonyms that land in "
      "different batches and get slightly different names survive as two one-instance "
      "concepts. That is also the cause of the one causal cycle in the graph "
      "(`graph_consistency.json`): three near-synonyms of self-explanation left separate. "
      "Normalisation now runs a guarded reconciliation pass afterwards — a researcher-"
      "declarable merge table in `config/concept_merges.yaml`, plus a subset rule that "
      "**refuses** to merge labels differing in polarity or degree, because "
      "\"prior knowledge\" and \"low prior knowledge\" are not the same concept.")
    w("")
    w("**Richmond itself is not corrected, deliberately.** Re-running normalisation would "
      "renumber the graph every published figure rests on, so the fix prevents recurrence "
      "rather than rewriting the record. The declared merges for Richmond are written down "
      "in the config and marked inert.")
    w("")
    w("**The four `role` verdicts are the ones worth a human's attention.** Two are labels "
      "that contradict their own quotes, which is the same class of error as the "
      "verification matcher defect found in November — a label asserting one polarity over "
      "evidence showing the other. Two are entities filed under the wrong role, including a "
      "moderation finding filed as an outcome when it is a context condition. None of the "
      "four would be caught by any count; each needed its quote read.")
    w("")
    w("**What would make this a measurement rather than a triage:** a second coder, "
      "preferably human, on the same 79 with the same five categories, and a positive "
      "specific agreement between the two. That is the method this project already used "
      "for the gold standard, and it costs time rather than money.")
    w("")

    out = PROJECT_ROOT / "outputs" / "analysis" / "PRECISION_SAMPLE.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(L)} lines -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
